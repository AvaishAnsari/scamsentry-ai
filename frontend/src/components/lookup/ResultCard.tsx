import React, { useState } from 'react';
import { Link } from 'react-router-dom';
import {
  Copy,
  Check,
  Share2,
  AlertOctagon,
  Calendar,
  CornerDownRight,
  ShieldCheck,
  PlusCircle,
  Clock,
  ShieldAlert,
} from 'lucide-react';
import { LookupResult } from '../../types';
import { VerdictBadge } from './VerdictBadge';

interface ResultCardProps {
  result: LookupResult;
}

export const ResultCard: React.FC<ResultCardProps> = ({ result }) => {
  const [copiedValue, setCopiedValue] = useState(false);
  const [sharedWarning, setSharedWarning] = useState(false);

  const copyToClipboard = (text: string) => {
    navigator.clipboard.writeText(text);
    setCopiedValue(true);
    setTimeout(() => setCopiedValue(false), 2000);
  };

  const handleShare = () => {
    const shareText = `⚠️ ScamSentry Alert: Check ${result.query}! Community verdict: ${result.verdict}. Reports: ${result.report_count}. Check before you trust: https://scamsentry.in/check?q=${encodeURIComponent(result.query)}`;
    
    if (navigator.share) {
      navigator.share({
        title: `ScamSentry Risk Alert for ${result.query}`,
        text: shareText,
        url: window.location.href,
      }).catch(() => {});
    } else {
      navigator.clipboard.writeText(shareText);
      setSharedWarning(true);
      setTimeout(() => setSharedWarning(false), 2500);
    }
  };

  const isScam = result.verdict === 'KNOWN_SCAM';
  const isSuspicious = result.verdict === 'SUSPICIOUS';
  const isUnderReview = result.verdict === 'UNDER_REVIEW';
  const isVerified = result.verdict === 'VERIFIED_BUSINESS';
  const isNoReports = result.verdict === 'NO_REPORTS';

  const cardBorderColor = isScam
    ? 'border-risk-red/30'
    : isSuspicious
    ? 'border-risk-amber/30'
    : isUnderReview
    ? 'border-amber-300'
    : isVerified
    ? 'border-risk-green/30'
    : 'border-line';

  const cardBg = isScam
    ? 'bg-gradient-to-b from-risk-red-tint/30 to-white'
    : isSuspicious
    ? 'bg-gradient-to-b from-risk-amber-tint/30 to-white'
    : isUnderReview
    ? 'bg-gradient-to-b from-amber-50/50 to-white'
    : isVerified
    ? 'bg-gradient-to-b from-risk-green-tint/30 to-white'
    : 'bg-white';

  return (
    <div className={`rounded-card border ${cardBorderColor} ${cardBg} p-5 sm:p-7 shadow-sm space-y-6 transition-all`}>
      {/* Top Bar: Verdict Badge + Risk Level */}
      <div className="flex flex-wrap items-center justify-between gap-3">
        <VerdictBadge verdict={result.verdict} size="lg" />

        <div className="flex items-center gap-2">
          {result.is_mock && (
            <span
              className="text-[11px] font-semibold text-amber-800 bg-amber-100 border border-amber-300 px-2 py-0.5 rounded-full"
              title="This result was generated by the frontend mock engine for hackathon demonstration."
            >
              Demo Simulation
            </span>
          )}

          <span
            className={`text-xs font-bold px-2.5 py-1 rounded-full ${
              isScam
                ? 'bg-risk-red text-white'
                : isSuspicious
                ? 'bg-risk-amber text-white'
                : isUnderReview
                ? 'bg-amber-500 text-white'
                : isVerified
                ? 'bg-risk-green text-white'
                : 'bg-gray-200 text-ink-muted'
            }`}
          >
            {isScam
              ? 'High risk'
              : isSuspicious
              ? 'Medium risk'
              : isUnderReview
              ? 'Low risk · Under review'
              : isVerified
              ? 'Low risk · Official'
              : 'Not enough data'}
          </span>
        </div>
      </div>

      {/* Target Identifier Display */}
      <div className="flex items-center justify-between border-b border-line pb-4">
        <div>
          <span className="text-xs uppercase font-bold text-ink-muted block tracking-wider mb-1">
            Checked Identifier ({result.target_type})
          </span>
          <div className="flex items-center gap-3">
            <h2 className="text-2xl sm:text-3xl font-bold font-mono tracking-tight text-ink">
              {result.query}
            </h2>
            <button
              onClick={() => copyToClipboard(result.query)}
              className="p-1.5 text-ink-muted hover:text-ink hover:bg-gray-100 rounded-btn transition-colors"
              title="Copy to clipboard"
              aria-label="Copy identifier"
            >
              {copiedValue ? (
                <Check className="w-4 h-4 text-emerald-600" />
              ) : (
                <Copy className="w-4 h-4" />
              )}
            </button>
          </div>
        </div>

        {/* Small Risk Gauge */}
        <div className="text-right">
          <span className="text-xs text-ink-muted block font-medium">Risk Score</span>
          <span
            className={`text-2xl font-bold ${
              isScam
                ? 'text-risk-red'
                : isSuspicious
                ? 'text-risk-amber'
                : isUnderReview
                ? 'text-amber-600'
                : isVerified
                ? 'text-risk-green'
                : 'text-ink-muted'
            }`}
          >
            {result.risk_score}
            <span className="text-xs text-ink-muted font-normal">/100</span>
          </span>
        </div>
      </div>

      {/* Primary Narrative Summary */}
      <div className="text-sm text-ink leading-relaxed font-medium">
        {isScam && (
          <p className="text-risk-red font-semibold">
            {result.report_count} people reported this identifier as a scam in the last 90 days.
            {result.first_reported && ` First report registered on ${new Date(result.first_reported).toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' })}.`}
          </p>
        )}
        {isSuspicious && (
          <p className="text-amber-900 font-semibold">
            {result.report_count} people reported unusual behavior for this identifier in the last 30 days. It is under community review, but caution is advised.
          </p>
        )}
        {isUnderReview && (
          <div className="bg-amber-50 border border-amber-200 rounded-card p-4 space-y-1.5 text-amber-950 text-xs">
            <div className="flex items-center gap-2">
              <Clock className="w-4 h-4 text-amber-700 shrink-0" />
              <p className="font-bold text-sm text-amber-900">
                Community Warning Registered ({result.report_count} Report)
              </p>
            </div>
            <p className="leading-relaxed">
              This creates a community warning. It does <strong>not</strong> automatically prove that the target is a confirmed scam. Additional independent corroborating reports are required to verify fraud patterns.
            </p>
            {result.top_category && (
              <p className="text-amber-800 font-semibold pt-1">
                Reported category: <span className="capitalize">{result.top_category.replace(/_/g, ' ')}</span>
              </p>
            )}
          </div>
        )}
        {isVerified && (
          <div className="flex items-start gap-2 text-emerald-900">
            <ShieldCheck className="w-5 h-5 text-risk-green shrink-0 mt-0.5" />
            <div>
              <p className="font-semibold">
                Matches the published official directory for {result.business_name || 'Verified Enterprise'}.
              </p>
              <p className="text-xs text-emerald-700 mt-1">
                Verified category: {result.business_category} · Source checked on {result.verified_date || 'October 2026'}.
              </p>
            </div>
          </div>
        )}
        {isNoReports && (
          <div className="bg-gray-50 border border-line rounded-card p-4 space-y-2 text-ink-muted text-xs">
            <p className="font-semibold text-ink text-sm">
              Nobody has reported this identifier so far.
            </p>
            <p>
              <strong>Important:</strong> "No reports yet" does <em>not</em> mean it is safe. Many fraud rings switch SIM cards or UPI IDs within hours of launching an attack.
            </p>
            <p className="text-gray-600">
              Before proceeding: Always verify identity independently. Never share banking PINs, OTPs, or install remote access software.
            </p>
          </div>
        )}
      </div>

      {/* Metrics Row (Reports, Areas, Recency, Status) */}
      {!isNoReports && !isVerified && (
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
          <div className="bg-white border border-line rounded-btn p-3 text-center">
            <span className="block text-2xl font-bold text-ink">{result.report_count}</span>
            <span className="text-xs text-ink-muted">Total reports</span>
          </div>
          <div className="bg-white border border-line rounded-btn p-3 text-center">
            <span className="block text-2xl font-bold text-ink">{result.independent_report_count ?? result.report_count}</span>
            <span className="text-xs text-ink-muted">Independent reporters</span>
          </div>
          <div className="bg-white border border-line rounded-btn p-3 text-center">
            <span className="block text-2xl font-bold text-ink">
              {result.distinct_areas || result.distinct_areas_count || 1}
            </span>
            <span className="text-xs text-ink-muted">Distinct areas</span>
          </div>
          <div className="bg-white border border-line rounded-btn p-3 text-center">
            <span
              className={`block text-2xl font-bold ${
                isScam ? 'text-risk-red' : isUnderReview ? 'text-amber-600' : 'text-amber-500'
              }`}
            >
              {isScam ? 'Flagged' : isUnderReview ? 'Review' : 'Watch'}
            </span>
            <span className="text-xs text-ink-muted">Status</span>
          </div>
        </div>
      )}

      {/* URL Specific Metadata if applicable */}
      {result.target_type === 'url' && (result.domain_registered_days_ago !== undefined || result.redirects_count !== undefined) && (
        <div className="grid grid-cols-2 gap-3 text-xs">
          {result.domain_registered_days_ago !== undefined && (
            <div className="flex items-center gap-2 bg-white border border-line p-3 rounded-btn">
              <Calendar className="w-4 h-4 text-ink-muted shrink-0" />
              <div>
                <span className="font-bold text-ink block">{result.domain_registered_days_ago} days ago</span>
                <span className="text-ink-muted text-[11px]">Domain registered (very new)</span>
              </div>
            </div>
          )}
          {result.redirects_count !== undefined && (
            <div className="flex items-center gap-2 bg-white border border-line p-3 rounded-btn">
              <CornerDownRight className="w-4 h-4 text-ink-muted shrink-0" />
              <div>
                <span className="font-bold text-ink block">{result.redirects_count} redirects</span>
                <span className="text-ink-muted text-[11px]">Obfuscated hops before landing</span>
              </div>
            </div>
          )}
        </div>
      )}

      {/* Breakdown of What People Reported */}
      {result.category_breakdown && result.category_breakdown.length > 0 && (
        <div className="space-y-2">
          <span className="text-xs font-bold uppercase tracking-wider text-ink-muted block">
            Reported Attack Patterns
          </span>
          <div className="flex flex-wrap gap-2">
            {result.category_breakdown.map((item, idx) => (
              <span
                key={idx}
                className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-full text-xs font-semibold bg-white border border-line text-ink"
              >
                <span>{item.name}</span>
                <span className="bg-surface px-1.5 py-0.5 rounded-full text-[11px] text-ink-muted font-mono font-bold">
                  {item.count}
                </span>
              </span>
            ))}
          </div>
        </div>
      )}

      {/* Safety Guidance: What to do */}
      <div className="bg-surface border border-line rounded-card p-4 space-y-2.5">
        <h4 className="text-xs font-bold uppercase tracking-wider text-ink flex items-center gap-1.5">
          <AlertOctagon className="w-4 h-4 text-brand" />
          Recommended Safety Guidance
        </h4>
        <ul className="text-xs text-ink space-y-1.5 list-disc list-inside">
          {result.safety_guidance && result.safety_guidance.length > 0 ? (
            result.safety_guidance.map((tip, idx) => (
              <li key={idx} className="leading-relaxed">
                {tip}
              </li>
            ))
          ) : isScam ? (
            <>
              <li>Do not pick up, or hang up immediately if on call.</li>
              <li>Never share OTP, ATM PIN, UPI PIN, or bank passwords.</li>
              <li>Do not download AnyDesk, RustDesk, or any APK files sent by this contact.</li>
              <li>
                <strong>Lost money?</strong> Call <strong>1930</strong> immediately to initiate banking cyber freeze.
              </li>
            </>
          ) : isSuspicious || isUnderReview ? (
            <>
              <li>Exercise extreme caution. Do not make advance payments for unverified services.</li>
              <li>Receiving money via UPI <em>never</em> requires entering your PIN.</li>
              <li>Independently verify sender phone numbers through official bank or company portals.</li>
            </>
          ) : isVerified ? (
            <>
              <li>Legitimate bank representatives will <strong>never</strong> ask for your PIN, OTP, or CVV.</li>
              <li>If the caller asks for sensitive financial credentials, hang up and call the bank branch directly.</li>
            </>
          ) : (
            <>
              <li>Always check the recipient account name before confirming any UPI payment.</li>
              <li>Be suspicious of unsolicited offers, urgency threats, or electricity disconnection SMS.</li>
              <li>Were you contacted suspiciously by this identifier? Report it to help protect others.</li>
            </>
          )}
        </ul>
      </div>

      {/* Community Impact message */}
      {result.community_impact_message && (
        <div className="bg-emerald-50/70 border border-emerald-200 rounded-btn p-3 text-xs text-emerald-900 flex items-start gap-2">
          <ShieldAlert className="w-4 h-4 text-emerald-700 shrink-0 mt-0.5" />
          <span>{result.community_impact_message}</span>
        </div>
      )}

      {/* Primary Actions: Report & Share Warning */}
      <div className="flex flex-col sm:flex-row items-center gap-3 pt-2">
        <Link
          to={`/report?type=${result.target_type}&val=${encodeURIComponent(result.query)}`}
          className="w-full sm:w-auto flex-1 h-11 px-5 bg-brand hover:bg-brand-hover text-white font-semibold text-xs sm:text-sm rounded-btn transition-colors flex items-center justify-center gap-2 shadow-sm"
        >
          <PlusCircle className="w-4 h-4" />
          <span>Report this {result.target_type === 'phone' ? 'Number' : result.target_type === 'upi' ? 'UPI ID' : 'Link'}</span>
        </Link>

        <button
          type="button"
          onClick={handleShare}
          className="w-full sm:w-auto h-11 px-5 bg-white hover:bg-surface text-ink font-semibold text-xs sm:text-sm rounded-btn border border-line transition-colors flex items-center justify-center gap-2 shadow-sm"
        >
          {sharedWarning ? (
            <>
              <Check className="w-4 h-4 text-emerald-600" />
              <span>Warning Copied!</span>
            </>
          ) : (
            <>
              <Share2 className="w-4 h-4 text-brand" />
              <span>Share Warning Link</span>
            </>
          )}
        </button>
      </div>

      <div className="text-[11px] text-ink-muted text-center pt-2">
        Based on community signals, heuristic indicators, and public threat feeds. Not a judicial finding.
      </div>
    </div>
  );
};
